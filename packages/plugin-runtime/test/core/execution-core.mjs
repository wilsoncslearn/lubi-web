import assert from 'node:assert/strict';
import { blankTask, executorOf, backgroundRun, backgroundRuntimeMs, withBackgroundPhase, prepareExecutionSave, backgroundEntries, dayTimeStats } from '../.out/core.mjs';

const date = '2026-10-14', later = '2026-10-15', origin = Date.parse('2026-10-14T01:00:00Z');
const legacy = blankTask({ id: 'legacy', title: '原任务', category: '学习', custom: { keep: true } });
assert.equal(executorOf(legacy), 'self');
assert.equal(legacy.executor, undefined);
assert.deepEqual(backgroundEntries([legacy], 'running'), []);
assert.throws(() => withBackgroundPhase(legacy, date, 'running', origin), /执行方式/);
let task = blankTask({ id: 'agent', title: '后台任务', executor: 'background', category: '日常' });
task = withBackgroundPhase(task, date, 'running', origin);
assert.equal(backgroundRun(task, date).phase, 'running');
assert.equal(backgroundRuntimeMs(backgroundRun(task, date), origin + 7200000), 7200000);
assert.equal(task.estimate, 0);
assert.equal(task.date, '');
assert.equal(task.status, 'todo', 'pure state helper does not complete or schedule');
assert.equal(withBackgroundPhase(task, date, 'running', origin + 1000), task, 'same transition is idempotent');
assert.throws(() => withBackgroundPhase(task, 'invalid', 'review', origin), /日期/);
assert.throws(() => withBackgroundPhase(task, date, 'unknown', origin), /状态/);
task = withBackgroundPhase(task, date, 'review', origin + 7200000);
assert.equal(backgroundRuntimeMs(backgroundRun(task, date), origin + 10800000), 7200000, 'review waiting is not running');
assert.equal(backgroundEntries([task], 'review').length, 1);
task = withBackgroundPhase(task, date, 'ready', origin + 10800000);
task = withBackgroundPhase(task, date, 'running', origin + 14400000);
task = withBackgroundPhase(task, date, 'review', origin + 16200000);
assert.equal(backgroundRuntimeMs(backgroundRun(task, date)), 9000000, 'rework accumulates only marked running intervals');
const edited = prepareExecutionSave({ ...task, notes: '人工备注', backgroundRuns: undefined }, task, origin + 18000000);
assert.equal(backgroundRuntimeMs(backgroundRun(edited, date)), 9000000, 'ordinary form edits retain latest runtime metadata');
const accepted = prepareExecutionSave({ ...task, status: 'done', date }, task, origin + 18000000);
assert.equal(backgroundRun(accepted, date).phase, 'accepted');
assert.equal(backgroundEntries([accepted], 'review').length, 0);
const reopened = prepareExecutionSave({ ...accepted, status: 'todo' }, accepted, origin + 19000000);
assert.equal(backgroundRun(reopened, date).phase, 'review');
const running = withBackgroundPhase(task, date, 'running', origin + 20000000);
const self = prepareExecutionSave({ ...running, executor: 'self' }, running, origin + 21000000);
assert.equal(backgroundRun(self, date).phase, 'ready');
assert.equal(backgroundEntries([self], 'running').length, 0);
assert.equal(backgroundRuntimeMs(backgroundRun(self, date), origin + 30000000), 10000000, 'switching to self stops annotation without deleting accumulated time');
let repeat = blankTask({ id: 'repeat', executor: 'background', repeat: { kind: 'daily', days: [] }, doneDates: [] });
repeat = withBackgroundPhase(repeat, date, 'review', origin);
repeat = withBackgroundPhase(repeat, later, 'running', origin);
assert.equal(backgroundEntries([repeat], 'review')[0].date, date);
assert.equal(backgroundEntries([repeat], 'running')[0].date, later);
const repeatAccepted = prepareExecutionSave({ ...repeat, doneDates: [date] }, repeat, origin + 1000);
assert.equal(backgroundRun(repeatAccepted, date).phase, 'accepted');
assert.equal(backgroundRun(repeatAccepted, later).phase, 'running');
const changedRule = prepareExecutionSave({ ...repeat, repeat: { kind: 'weekly', days: [1] } }, repeat, origin + 2000);
assert.equal(changedRule.backgroundRuns[later].phase, 'ready', 'rule change cannot leave hidden running annotations');
const personal = dayTimeStats([{ start: '09:00', minutes: 60 }]);
assert.equal(personal.recordedMinutes, 60);
assert.equal(personal.coveredMinutes, 60);
assert.equal(personal.overlapMinutes, 0, 'Agent runtime never enters personal-time metrics');
assert.equal(backgroundRuntimeMs({ ...backgroundRun(task, date), runtimeMs: NaN }), 0);
assert.equal(backgroundRuntimeMs({ ...backgroundRun(task, date), phase: 'running', startedAt: 'bad timestamp', runtimeMs: 12 }), 12);
assert.equal(backgroundRuntimeMs({ ...backgroundRun(task, date), phase: 'running', startedAt: new Date(origin + 1000).toISOString(), runtimeMs: 12 }, origin), 12, 'clock rollback never produces negative time');
console.log('PASS execution core: legacy defaults, manual clocks, no inferred plans, review/rework/acceptance, recurrence isolation, latest-metadata preservation and personal-time separation');
